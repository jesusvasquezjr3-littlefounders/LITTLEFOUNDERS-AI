#!/usr/bin/env bash
# Regenerates repo_map.md: directory tree + first 15 lines of every source file.
# Run from anywhere: npm run repo:map
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="repo_map.md"
# Pruned by NAME at any depth (per-service node_modules/dist/coverage included):
EXCLUDE_NAMES=(.git node_modules dist coverage .claude .agents .codex LEGAL .vscode .branches .temp duckdb)
# Pruned by exact PATH from root:
EXCLUDE_PATHS=(.github/skills database/supabase)
INCLUDE_EXT=(ts tsx js jsx json sql md sh yml yaml css html toml)

PRUNE_ARGS=()
for d in "${EXCLUDE_NAMES[@]}"; do PRUNE_ARGS+=(-name "$d" -prune -o); done
for d in "${EXCLUDE_PATHS[@]}"; do PRUNE_ARGS+=(-path "./$d" -prune -o); done

{
  echo "# repo_map.md — LittleFounders Repository Map"
  echo
  echo "> AUTO-GENERATED by scripts/update-repo-map.sh on $(date +%Y-%m-%d). Do not edit by hand."
  echo "> Tree + first 15 lines of each source file. Never paste this whole file into a prompt — search it."
  echo
  echo '## Directory tree'
  echo
  echo '```'
  find . "${PRUNE_ARGS[@]}" -type d -print | sed 's|^\./||' | sort | grep -v '^\.$' | awk -F/ '{ indent=""; for(i=1;i<NF;i++) indent=indent "  "; print indent $NF "/" }'
  echo '```'
  echo
  echo '## File previews (first 15 lines)'

  NAME_ARGS=()
  for e in "${INCLUDE_EXT[@]}"; do NAME_ARGS+=(-name "*.$e" -o); done
  unset 'NAME_ARGS[${#NAME_ARGS[@]}-1]'

  find . "${PRUNE_ARGS[@]}" -type f \( "${NAME_ARGS[@]}" \) -print | sed 's|^\./||' | sort | while IFS= read -r f; do
    case "$f" in
      repo_map.md|*package-lock.json) continue ;;
    esac
    echo
    echo "### $f"
    echo
    echo '```'
    head -n 15 "$f" 2>/dev/null || true
    echo '```'
  done
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
