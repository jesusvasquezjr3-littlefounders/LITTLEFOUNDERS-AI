#!/usr/bin/env node
/**
 * Horizonte Visual packs: the pure part of every pack (contract, model, scorer, fixtures, the shared helpers and
 * types) is canonical in backend/src/services/horizonte and copied to frontend/src/rebuild/learning/horizonte as
 * `<name>.generated.ts`, so Core and the browser parse and score with the very same code.
 *
 * Not copied: `index.ts` and `capabilities.ts` (assembled by hand per layer; the capability literals are held in
 * parity by check-v2-lesson-capability-parity.mjs), `harness/` and every `*.test.ts`.
 * `--check` fails on any drift, including a copy whose source is gone. Regenerate instead of merging by hand.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const sourceRoot = resolve(root, 'backend/src/services/horizonte');
const targetRoot = resolve(root, 'frontend/src/rebuild/learning/horizonte');
const learningRoot = resolve(root, 'frontend/src/rebuild/learning');
const HAND_ASSEMBLED = new Set(['index.ts', 'capabilities.ts']);
const GENERATED = /\.generated\.ts$/;

const posix = (file) => file.split('\\').join('/');

export function syncedSources(dir = sourceRoot) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'harness') continue;
      out.push(...syncedSources(full));
    } else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts') && !HAND_ASSEMBLED.has(entry.name)) out.push(full);
  }
  return out.sort();
}

export function generatedPath(source) {
  return join(targetRoot, relative(sourceRoot, source).replace(/\.ts$/, '.generated.ts'));
}

function header(source) {
  return `/* Generated by agent/tools/sync-v2-horizonte.mjs from ${posix(relative(root, source))}. Do not edit: change the source and regenerate. */\n`;
}

export function render(source, sources = syncedSources()) {
  const synced = new Set(sources.map(posix));
  const text = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
  const body = text.replace(/(from\s+|import\s*\(\s*)'(\.{1,2}\/[^']+)\.js'/g, (match, lead, spec) => {
    const target = resolve(dirname(source), `${spec}.ts`);
    const browserTarget = resolve(dirname(generatedPath(source)), `${spec}.generated.ts`);
    const hasCopy = synced.has(posix(target)) || (browserTarget.startsWith(learningRoot) && !browserTarget.startsWith(targetRoot) && existsSync(browserTarget));
    if (!hasCopy) throw new Error(`${posix(relative(root, source))}: import '${spec}.js' has no browser copy; keep synced files free of hand-assembled imports`);
    return `${lead}'${spec}.generated'`;
  });
  return header(source) + body;
}

function staleCopies() {
  const expected = new Set(syncedSources().map((source) => posix(generatedPath(source))));
  const found = [];
  const walk = (dir) => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (GENERATED.test(entry.name) && !expected.has(posix(full))) found.push(full);
    }
  };
  walk(targetRoot);
  return found;
}

const check = process.argv.includes('--check');
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sources = syncedSources();
  const drift = [];
  for (const source of sources) {
    const target = generatedPath(source);
    const next = render(source, sources);
    if (check) {
      if (!existsSync(target) || readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== next) drift.push(posix(relative(root, target)));
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, next);
    }
  }
  for (const stale of staleCopies()) {
    if (check) drift.push(`${posix(relative(root, stale))} (no source)`);
    else rmSync(stale);
  }
  if (check) {
    if (drift.length) {
      console.error(`Horizonte generated copies drift (run node agent/tools/sync-v2-horizonte.mjs):\n  ${drift.join('\n  ')}`);
      process.exitCode = 1;
    } else console.log(`Horizonte pack sync parity OK (${sources.length} files).`);
  } else console.log(`Generated ${sources.length} Horizonte browser copies from the canonical Core packs.`);
}
